#!/bin/sh
# Regenerates Packages/RiveViewerKit/Sources/RiveViewerKit/RiveSchema.swift from the Rive runtime's
# generated C++ headers: type keys and property keys from the *_base.hpp files, and each property's
# storage kind from CoreRegistry::propertyFieldId in core_registry.hpp.
#
# Usage: Scripts/generate-rive-schema.sh [path-to-rive-runtime-checkout]
# Without an argument the script makes a shallow sparse clone of rive-app/rive-runtime in a temp dir.
set -e

ROOT=$(cd "$(dirname "$0")/.." && pwd)
OUT="$ROOT/Packages/RiveViewerKit/Sources/RiveViewerKit/RiveSchema.swift"
SRC=${1:-}

if [ -z "$SRC" ]; then
  TMP=$(mktemp -d)
  git clone -q --depth 1 --filter=blob:none --sparse https://github.com/rive-app/rive-runtime.git "$TMP/repo"
  (cd "$TMP/repo" && git sparse-checkout set include/rive/generated >/dev/null)
  SRC="$TMP/repo"
fi

GEN="$SRC/include/rive/generated"
[ -f "$GEN/core_registry.hpp" ] || { echo "No generated headers at $GEN" >&2; exit 1; }
COMMIT=$(cd "$SRC" && git rev-parse --short HEAD 2>/dev/null || echo unknown)

PERL_PROGRAM=$(cat <<'PERL'
my $registry = shift @ARGV;
my (%types, %props, %lookup, %kinds);
for my $file (@ARGV) {
  open my $fh, "<", $file or next;
  my $class;
  while (<$fh>) {
    if (/class (\w+)Base\b/) { $class = $1 }
    elsif (defined $class && /static const uint16_t typeKey = (\d+);/) { $types{$1} = $class }
    elsif (defined $class && /static const uint16_t (\w+)PropertyKey = (\d+);/) { $props{$2} = "$class.$1"; $lookup{"${class}Base::$1"} = $2 }
  }
  close $fh;
}
open my $rh, "<", $registry or die "cannot read $registry";
my ($inside, @pending) = (0);
while (<$rh>) {
  if (/static int propertyFieldId\(int propertyKey\)/) { $inside = 1; next }
  next unless $inside;
  if (/case (\w+Base::\w+)PropertyKey:/) { push @pending, $1 }
  elsif (/return Core(\w+)Type::id;/) { for my $label (@pending) { $kinds{$lookup{$label}} = $1 if defined $lookup{$label} } @pending = () }
  elsif (/^  }/) { last }
}
print "    public static let typeNames: [Int: String] = [\n";
print "        $_: \"$types{$_}\",\n" for sort { $a <=> $b } keys %types;
print "    ]\n\n";
print "    public static let propertyNames: [Int: String] = [\n";
print "        $_: \"$props{$_}\",\n" for sort { $a <=> $b } keys %props;
print "    ]\n\n";
print "    /// Storage kind of each property (Uint, Id, Bool, Int, String, Bytes, Double or Color), from CoreRegistry::propertyFieldId.\n";
print "    public static let propertyKinds: [Int: String] = [\n";
print "        $_: \"$kinds{$_}\",\n" for sort { $a <=> $b } keys %kinds;
print "    ]\n";
PERL
)

{
  echo "// Generated by Scripts/generate-rive-schema.sh from rive-app/rive-runtime@$COMMIT (include/rive/generated)."
  echo "// Do not edit by hand."
  echo ""
  echo "/// Names and storage kinds for the type keys and property keys found in a .riv file."
  echo "public enum RiveSchema {"
  find "$GEN" -name '*_base.hpp' | sort | xargs perl -e "$PERL_PROGRAM" "$GEN/core_registry.hpp"
  echo "}"
} > "$OUT"

echo "Wrote $OUT ($(grep -c ': "' "$OUT") entries)"
